#!/usr/bin/env node
// 生成案例包夹具：季度成本预算模型.xlsx —— 自造但拟真的教学用例。
//
//   node fixtures/make-case.mjs   （cwd 在案例包目录下）
//
// 四张表：假设、明细、汇总、说明。种入若干缺陷，展示方言"能查到什么"
// 与"明知查不到什么"。缺陷清单见上级任务说明，本文件只负责照办生成。

import { writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { buildXlsx } from '../../../adapters/xlsx/write.mjs'

const HERE = dirname(fileURLToPath(import.meta.url))

// ── 假设 ────────────────────────────────────────────────────────
const 假设 = {
  A1: 's:项目', B1: 's:值',
  A2: 's:税率', B2: 0.06,
  A3: 's:折扣率', B3: 0.05,
  A4: 's:汇率', B4: 7.1,
  A5: 's:单价基准（元）', B5: 1000, // 缺陷 D8：数量级错误（应为约10~20元），刻意不修，不可检
}

// ── 明细 ────────────────────────────────────────────────────────
const B = [120, 135, 110, 128, 140, 150, 132, 145, 138, 160, 155, 148] // 下标0对应行2
const C = [15.5, 16.0, 15.8, 16.2, 15.9, 16.5, 16.8, 16.3, 16.0, 17.0, 16.9, 17.2]
const months = ['1月', '2月', '3月', '4月', '5月', '6月', '7月', '8月', '9月', '10月', '11月', '12月']

const 明细 = {
  A1: 's:月份', B1: 's:数量', C1: 's:单价', D1: 's:金额', E1: 's:税额', F1: 's:小计', G1: 's:毛利率(示例)',
}

for (let i = 0; i < 12; i++) {
  const row = i + 2
  明细[`A${row}`] = `s:${months[i]}`
  // B4（行4，i=2）例外：文本型数字 —— 缺陷 D6
  明细[`B${row}`] = (row === 4) ? 's:110' : B[i]
  明细[`C${row}`] = C[i]
}

// D 列：共享公式列，D = B*C，D9 硬编码、D12 文本粘贴例外
const dVals = { 2: 1860, 3: 2160, 4: 1738, 5: 2073.6, 6: 2226, 7: 2475, 8: 2217.6, 10: 2208, 11: 2720, 13: 2545.6 }
明细.D2 = { f: 'B2*C2', v: 1860, si: 0, ref: 'D2:D13' }
for (const row of [3, 4, 5, 6, 7, 8, 10, 11, 13]) {
  明细[`D${row}`] = { si: 0, v: dVals[row] }
}
明细.D9 = 2300 // 缺陷 D1：公式列混入硬编码常量（正确值应为2363.5）
明细.D12 = 's:见附注' // 缺陷 D9：文本粘贴到公式格，明确查不到

// E 列：共享公式列，"税额"，整列错误引用折扣率而非税率 —— 缺陷 D7
const eVals = { 3: 108, 4: 86.9, 5: 103.68, 6: 111.3, 7: 123.75, 8: 110.88, 9: 115, 10: 110.4, 11: 136, 13: 127.28 }
明细.E2 = { f: 'D2*假设!$B$3', v: 93, si: 1, ref: 'E2:E13' }
for (const row of [3, 4, 5, 6, 7, 8, 9, 10, 11, 13]) {
  明细[`E${row}`] = { si: 1, v: eVals[row] }
}
明细.E12 = { si: 1, v: 0 } // D12 为文本无数值

// F 列：共享公式列，"小计"，F = D+E，F7 例外为独立公式（引用错行）—— 缺陷 D2
const fVals = { 3: 2268, 4: 1824.9, 5: 2177.28, 6: 2337.3, 8: 2328.48, 9: 2415, 10: 2318.4, 11: 2856, 12: 0, 13: 2672.88 }
明细.F2 = { f: 'D2+E2', v: 1953, si: 2, ref: 'F2:F13' }
for (const row of [3, 4, 5, 6, 8, 9, 10, 11, 12, 13]) {
  明细[`F${row}`] = { si: 2, v: fVals[row] }
}
明细.F7 = { f: 'D7+E6', v: 2586.3 } // 缺陷 D2：同列公式形状不一致，警告级

// G 列：错误值残留 —— 缺陷 D4
明细.G5 = { f: 'D5/(C5-C5)', v: '#DIV/0!', e: true }

// 第14行 合计
明细.A14 = 's:合计'
明细.B14 = { f: 'SUM(B2:B12)', v: 1423 } // 缺陷 D3：求和漏掉第13行
明细.D14 = { f: 'SUM(D2:D13)', v: 24523.8 }
明细.E14 = { f: 'SUM(E2:E13)', v: 1226.19 }
明细.F14 = { f: 'SUM(F2:F13)', v: 25737.54 }

// ── 汇总 ────────────────────────────────────────────────────────
const 汇总 = {
  A1: 's:指标', B1: 's:数值',
  A2: 's:总数量', B2: { f: '明细!B14', v: 1423 },
  A3: 's:总小计（关键指标）', B3: { f: '明细!F14', v: 25737.54 },
  A4: 's:平均单价', B4: { f: '明细!D14/明细!B14', v: 17.23 },
  A5: 's:税负', B5: { f: '明细!E14/明细!D14', v: 0.05 },
  A6: 's:参考（勿删）', B6: { f: '旧汇总!C4', v: 0 }, // 缺陷 D5：引用不存在的工作表
}

// ── 说明 ────────────────────────────────────────────────────────
const 说明 = {
  A1: 's:季度成本预算模型 — 使用说明', // 模拟合并大标题，第1行
  A2: 's:序号', B2: 's:说明', // 真正的表头在第2行
  A3: 's:1', B3: 's:税率与折扣率见"假设"表，改动后需要重新核对"汇总"表。',
  A4: 's:参考区间', C4: 's:1,200', // 缺陷 D10：文本型数字但没有聚合覆盖它，明确查不到
  A5: 's:2', B5: 's:年度基准单价区间为 1,200–1,500 元/件（仅供参考，不参与计算）。',
}

if (process.argv[1]?.includes('make-case')) {
  const outDir = join(HERE, '..', 'payloads')
  mkdirSync(outDir, { recursive: true })
  const outFile = join(outDir, '季度成本预算模型.xlsx')
  writeFileSync(outFile, buildXlsx([
    { name: '假设', rows: 假设 },
    { name: '明细', rows: 明细 },
    { name: '汇总', rows: 汇总 },
    { name: '说明', rows: 说明 },
  ]))
  process.stderr.write(`已生成 ${outFile}\n`)
}
